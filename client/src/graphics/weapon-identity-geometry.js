export const expandedGeometry = (name, ancestry=[]) => {
    if(ancestry.includes(name))throw new Error(`Circular identity geometry ${[...ancestry,name].join(' -> ')}`);
    const nodes=IDENTITY_GEOMETRY[name];if(!nodes)return null;
    return nodes.map(node=>node.glyph?{...node,geometry:expandedGeometry(node.glyph,[...ancestry,name]),glyph:undefined}:node);
};

export const drawIdentityGeometry = (context,name,size=1,{fill=false}={}) => {
    const nodes=IDENTITY_GEOMETRY[name];if(!nodes)return false;
    for(const node of nodes){
        if(node.glyph){context.save();context.translate(node.x*size,node.y*size);context.rotate(node.angle);drawIdentityGeometry(context,node.glyph,size*node.scale,{fill});context.restore();continue;}
        context.beginPath();node.points.forEach(([x,y],index)=>index?context.lineTo(x*size,y*size):context.moveTo(x*size,y*size));
        if(node.closed){context.closePath();if(fill)context.fill();}context.stroke();
    }
    return true;
};
