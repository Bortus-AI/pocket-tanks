export const storyboardPose=(motion,progress,reducedMotion=false)=>{
    if(reducedMotion)return pose(0,0,0,1,1,1);
    return (IDENTITY_MOTIONS[motion]||IDENTITY_MOTIONS.strike)(clamp(progress));
};

// These transform the primary family geometry itself. Different materials do
// not share the same explosion with a colored particle badge on top.
export const MATERIAL_CHOREOGRAPHY = {
    ballistic:(p,quiet)=>[pose(0,0,quiet?0:p*.12,.35+p*.8,.35+p*.8,1-p*.25)],
    thermal:(p,quiet)=>[-1,0,1].map((side,index)=>pose(side*.3,quiet?-.2:-p*(index===1?.55:.3),side*.18,.48+index*.06,index===1?1.2:.8,1-p*.3)),
    crystalline:(p,quiet)=>[-1,0,1].map(side=>pose(side*.34,-Math.abs(side)*.12,side*.42,quiet?.7:.22+p*.65,quiet?1:.3+p*.9,1)),
    solvent:(p,quiet)=>[pose(0,quiet?.18:p*p*.48,quiet?0:Math.sin(p*Math.PI)*.09,1+p*.22,quiet?.7:1-p*.5,1-p*.45)],
    staccato:(p,quiet)=>[-1,0,1].map((side,index)=>pose(side*.48,side%2*.12,0,.33,1,quiet?1:(Math.floor(p*8)+index)%3===0?.2:1)),
    stratified:(p,quiet)=>[-1,0,1].map((side,index)=>pose(side*.55,quiet?index*.07:Math.sin(p*Math.PI+index)*.2,quiet?side*.1:side*p*.2,.6,.62,1)),
    returnflow:(p,quiet)=>[pose(quiet?-.3:-p*.65,0,0,quiet?1.35:1+p*.85,.9-p*.35,1)],
    pneumatic:(p,quiet)=>[-1,0,1].map(side=>pose(side*.4,quiet?-.12:-p*.12,0,quiet?.8:.25+p*.65,quiet?.85:.2+p*.8,1)),
    ferrous:(p,quiet)=>[-1,1].map(side=>{const angle=quiet?.3:(1-p)*Math.PI*.9;return pose(Math.cos(angle)*side*.5,Math.sin(angle)*side*.4,angle*side,.65,.65,1);}),
    unstable:(p,quiet)=>p<.3?[pose(0,0,quiet?0:p*-.4,.45+p,.45+p,1)]:[-1,1].map(side=>pose(side*(quiet?.45:(p-.3)*.9),side>0?-.18:.1,side*p*.4,side>0?.9:.55,side>0?.8:1.1,1-p*.3)),
};

export const materialActors=(primary,progress,reducedMotion=false)=>
    (MATERIAL_CHOREOGRAPHY[primary]||MATERIAL_CHOREOGRAPHY.ballistic)(clamp(progress),reducedMotion);
